# ===== 天气/季节修正 =====
BAD_WEATHER = {"暴雨", "大雪", "狂风", "雷暴", "冰雹", "沙尘暴"}
COLD_SEASONS = {"冬季"}


def _match_role_category(role: str) -> str | None:
    """根据 role 字段关键词匹配职业类别"""
    if not role:
        return None
    role_lower = role.lower()
    for category, keywords in ROLE_KEYWORDS.items():
        for kw in keywords:
            if kw in role or kw.lower() in role_lower:
                return category
    return None


def get_routine_template(npc: "NPCState", world_state: "WorldState") -> dict[str, tuple[str, str, int]] | None:
    """获取 NPC 对应的日程模板"""
    category = _match_role_category(npc.role or "")
    if category and category in ROUTINE_TEMPLATES:
        return ROUTINE_TEMPLATES[category]
    return DEFAULT_ROUTINE


def get_routine_action(
    npc: "NPCState",
    world_state: "WorldState",
) -> tuple[str, str, int] | None:
    """获取 NPC 当前时段的日程行动。

    Returns:
        (action, detail, energy_cost) 或 None（无日程）
    """
    time_slot = getattr(world_state, "current_time", "")
    if time_slot not in TIME_SLOTS:
        return None

    template = get_routine_template(npc, world_state)
    if not template or time_slot not in template:
        return None

    action, detail_tpl, energy_cost = template[time_slot]
    detail = detail_tpl.format(name=npc.name)

    # ── 天气修正 ──
    weather = getattr(world_state, "weather", "") or ""
    if weather in BAD_WEATHER and action not in ("歇息", "歇晌", "用饭", "用斋"):
        # 恶劣天气：户外活动改为留守
        detail = f"{npc.name}因{weather}留守室内，未做{action}。"
        action = "idle"
        energy_cost = 3

    # ── 季节修正（冬季减少户外活动）──
    season = getattr(world_state, "season", "") or ""
    if season in COLD_SEASONS and action in ("下田", "耕作", "狩猎", "捕鱼", "巡山", "采药", "晨练"):
        detail = f"{npc.name}畏寒不出，只在近处活动。"
        action = "idle"
        energy_cost = 3

    return (action, detail, energy_cost)


def get_routine_hint(npc: "NPCState", world_state: "WorldState") -> str:
    """构造日程提示，注入 LLM prompt（让 LLM 决策时考虑时段）。

    格式：「此刻是【上午】，按{职业}惯例应做【打铁】。」
    """
    time_slot = getattr(world_state, "current_time", "")
    if time_slot not in TIME_SLOTS:
        return ""

    routine = get_routine_action(npc, world_state)
    if not routine:
        return ""

    action, _, _ = routine
    category = _match_role_category(npc.role or "") or "常人"
    return f"【日程提示】此刻是{time_slot}，按{category}惯例应做「{action}」。可据目标与处境调整。"


def has_routine(npc: "NPCState") -> bool:
    """NPC 是否有日程模板（用于判断是否走日程分支）"""
    return _match_role_category(npc.role or "") is not None
